import { createRequire } from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.LOCALAPPDATA + '/ms-playwright-go/1.57.0/package');
const dir = '.codex-tmp/video-review';
const source = '/assets/videos/landimotos-demo-operativo.mp4';
const report = [];
const errors = [];
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  for (const [width, motion] of [[1440, 'no-preference'], [768, 'no-preference'], [390, 'reduce'], [320, 'reduce']]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 }, reducedMotion: motion });
    const requests = [];
    page.on('request', request => { if (request.url().includes(source)) requests.push(request.url()); });
    page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => localStorage.setItem('breckline-cookie-consent-v1', 'rejected'));
    await page.goto('http://127.0.0.1:3000/proyectos/portal-logistico-landimotos');
    await page.evaluate(() => document.fonts.ready);
    const video = page.locator('main section').first().locator('video');
    await video.scrollIntoViewIfNeeded();
    const before = await video.evaluate(v => ({ paused: v.paused, controls: v.controls, muted: v.muted, autoplay: v.autoplay, preload: v.preload, poster: v.getAttribute('poster'), playsInline: v.playsInline, width: v.getBoundingClientRect().width, height: v.getBoundingClientRect().height, time: v.currentTime }));
    assert(before.paused && before.controls && before.muted && !before.autoplay && before.playsInline);
    assert.equal(before.preload, 'none');
    assert.equal(before.time, 0);
    assert.equal(before.poster, '/assets/images/Intranet landimotos panel operativo.png');
    assert.deepEqual(requests, [], 'video is not downloaded before play');
    assert(Math.abs(before.width / before.height - 16 / 9) < 0.001);
    await page.addStyleTag({ content: 'nextjs-portal { display: none !important; }' });
    await video.screenshot({ path: `${dir}/poster-${width}.png` });
    await video.focus();
    await page.keyboard.press('Space');
    await page.waitForFunction(() => { const v = document.querySelector('main video'); return !v.paused && v.currentTime > 0.2; });
    await page.keyboard.press('Space');
    assert(await video.evaluate(v => v.paused), 'native pause control works from keyboard');
    const loaded = await video.evaluate(v => ({ duration: v.duration, width: v.videoWidth, height: v.videoHeight, layoutHeight: v.getBoundingClientRect().height, error: v.error?.message ?? null }));
    assert.equal(loaded.width, 2560);
    assert.equal(loaded.height, 1440);
    assert(Math.abs(loaded.duration - 111.471) < 0.1);
    assert(Math.abs(before.height - loaded.layoutHeight) < 1, 'poster and playback have stable dimensions');
    assert.equal(loaded.error, null);
    await video.evaluate(v => new Promise(resolve => { v.addEventListener('seeked', resolve, { once: true }); v.currentTime = 40; }));
    await video.screenshot({ path: `${dir}/playing-${width}.png` });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert.equal(overflow, false);
    const range = await page.request.get(`http://127.0.0.1:3000${source}`, { headers: { Range: 'bytes=0-1023' } });
    assert.equal(range.status(), 206);
    assert(range.headers()['content-type'].includes('video/mp4'));
    assert.equal((await range.body()).length, 1024);
    assert.equal(await page.locator('#procesos').count(), 1);
    report.push({ width, motion, before, loaded, range: range.status(), overflow });
    await page.close();
  }
  assert.deepEqual(errors, []);
  const bytes = fs.readFileSync('public/assets/videos/landimotos-demo-operativo.mp4');
  assert(bytes.indexOf(Buffer.from('moov')) < bytes.indexOf(Buffer.from('mdat')), 'fast-start metadata precedes video data');
  fs.writeFileSync(`${dir}/video-qa.json`, JSON.stringify({ report, errors, bytes: bytes.length }, null, 2));
  console.log(JSON.stringify({ status: 'passed', widths: report.map(item => item.width), bytes: bytes.length, errors }));
} finally { await browser.close(); }
